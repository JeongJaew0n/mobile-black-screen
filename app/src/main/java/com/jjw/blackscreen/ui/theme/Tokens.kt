package com.jjw.blackscreen.ui.theme

import androidx.compose.ui.graphics.Color

/**
 * 이 앱의 디자인 토큰. **반복해서 쓰이는 값만 여기 있다.**
 *
 * 차폐 화면의 규칙은 "검정 바탕에 흰 글자" 하나뿐이라 큰 팔레트가 필요 없다. 한 곳에서만
 * 쓰이는 값(겨냥 목표의 빨강·파랑, 시계 64sp, 번인 궤도 8dp×28dp 등)은 **일부러 여기로
 * 옮기지 않았다** — 그 값들은 "왜 이 값인가" 가 쓰이는 자리의 주석에 붙어 있어야 읽힌다.
 * 토큰으로 빼는 순간 근거가 코드에서 멀어진다.
 *
 * 여기 있는 것의 기준은 하나다: **같은 의도가 두 곳 이상에서 반복되는가.**
 */

/**
 * 다른 앱 위에 떠 있는 UI의 어두운 표면 — 버블, 그리고 설정에서 버블을 흉내 내는 미리보기.
 *
 * 알파 0xE0 는 뒤가 살짝 비쳐 "떠 있다" 는 인상을 준다. 불투명하면 화면에 붙은 딱지처럼 보인다.
 * 겨냥 목표(`AimTargets`)는 조금 더 밝고 흐린 `0xC0202020` 을 쓴다 — 버블보다 뒤로 물러나
 * 보여야 해서 일부러 다른 값이고, 그래서 여기 없다.
 */
val FloatingSurface = Color(0xE0141414)

/** 위 표면에 두르는 얇은 테두리. 항상 1dp 로 쓴다. 어두운 배경에서 윤곽만 잡아 준다. */
val FloatingBorder = Color(0x33FFFFFF)

/** 떠 있는 UI 위의 기호·라벨. 흰색을 70% 로 낮춰 표면에서 뜨지 않게 한다. */
val FloatingContent = Color(0xB3FFFFFF)

/**
 * 차폐 화면의 보조 텍스트 알파. 제목보다 한 단계 낮춘다.
 *
 * 색이 아니라 알파인 이유: 글자색은 설정이 정하는 `Settings.textColor` 라 고정할 수 없고,
 * 그 색을 기준으로 상대적으로 낮춰야 한다.
 */
const val SecondaryAlpha = 0.7f
